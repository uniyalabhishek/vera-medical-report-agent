const tables: Record<AppLanguage, MessageTable> = {
  English: english,
  Hindi: hindi,
  Tamil: tamil,
  Kannada: kannada,
  Marathi: marathi,
};

export function getMessages(language: AppLanguage): MessageTable {
  return tables[language] ?? tables.English;
}

export function message(
  language: AppLanguage,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    getMessages(language)[key],
  );
}

export function formatAppDate(language: AppLanguage, value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat(languageMeta[language].locale, {
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(date);
}

export function isSupportedLanguage(value: unknown): value is AppLanguage {
  return supportedLanguages.includes(value as AppLanguage);
}
